"""HTTP/browser regression checks. Uses synthetic form data and mocked external providers."""
from pathlib import Path
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from urllib.parse import urlsplit
import functools, json, threading
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1];OUT=ROOT/'test-results'/'seo';OUT.mkdir(parents=True,exist_ok=True)
class Handler(SimpleHTTPRequestHandler):
 def log_message(self,*args):pass
server=ThreadingHTTPServer(('127.0.0.1',0),functools.partial(Handler,directory=str(ROOT)))
threading.Thread(target=server.serve_forever,daemon=True).start();BASE='http://127.0.0.1:'+str(server.server_port)
urls=json.loads((ROOT/'seo-release.json').read_text())['public_urls'];checks=[];errors=[]
def passed(name):checks.append(name);print('PASS:',name,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
 context.tracing.start(screenshots=True,snapshots=True,sources=True)
 page=context.new_page();page.on('pageerror',lambda error:errors.append(str(error)))
 try:
  for u in urls:
   path=urlsplit(u).path
   response=page.goto(BASE+path,wait_until='domcontentloaded');assert response.status==200,path
   assert page.locator('html').get_attribute('lang')=='en-CA'
   assert page.locator('link[rel=canonical]').get_attribute('href')==u
   graph=json.loads(page.locator('#jowkari-entity-schema').text_content())['@graph']
   org=[x for x in graph if x.get('@type')=='Organization'];assert len(org)==1 and org[0]['@id']=='https://jowkaritech.com/#org'
   if path!='/jowkari-sites/':expect(page.locator('h1')).to_be_visible()
   assert page.locator('meta[name=robots]').get_attribute('content').startswith('index,follow')
  passed('all 25 indexable pages render with the right canonical, language and business entity')
  for width in [360,390,768,1440]:
   page.set_viewport_size({'width':width,'height':950})
   for path in ['/services.html','/about.html','/contact.html','/small-business-website-checklist.html','/website-design-north-vancouver.html','/website-designer-roofers.html','/website-designer-plumbers.html','/affordable-website-design-vancouver.html']:
    page.goto(BASE+path,wait_until='domcontentloaded');page.wait_for_timeout(100)
    fits=page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    if not fits:print('OVERFLOW',path,width,page.locator('body *').evaluate_all('(els)=>els.map(e=>({tag:e.tagName,cls:e.className,right:e.getBoundingClientRect().right,text:e.textContent.slice(0,45)})).filter(x=>x.right>innerWidth+1)'),flush=True)
    assert fits,path+' overflows '+str(width)
    if width in [390,1440] and path in ['/services.html','/contact.html','/website-design-north-vancouver.html']:
     page.screenshot(path=str(OUT/(path.strip('/').replace('.html','')+'-'+str(width)+'.png')),full_page=True)
   passed(str(width)+'px: new resource and priority service pages have no horizontal overflow')
  page.set_viewport_size({'width':1440,'height':1000})
  page.goto(BASE+'/');page.locator('.seo-footer-links a[href="/services.html"]').click();expect(page).to_have_url(BASE+'/services.html')
  page.locator('.seo-actions a[href="/website-design-north-vancouver.html"]').click();expect(page).to_have_url(BASE+'/website-design-north-vancouver.html')
  page.locator('.seo-breadcrumb a[href="/services.html"]').click();expect(page).to_have_url(BASE+'/services.html');passed('homepage to services to North Vancouver and breadcrumb return are clickable')
  page.goto(BASE+'/small-business-website-checklist.html');page.locator('a[href="#check-5"]').click();expect(page).to_have_url(BASE+'/small-business-website-checklist.html#check-5');passed('guide table of contents resolves to its real enquiry-check section')
  # The preview parameter is marked noindex even while its API is unavailable.
  context.route('https://jowkari-preview.jowkari-1mh.workers.dev/**',lambda route:route.abort('failed'))
  page.goto(BASE+'/jowkari-sites/?preview_id='+'a'*32,wait_until='domcontentloaded')
  expect(page.locator('meta[name=robots]').first).to_have_attribute('content','noindex,nofollow');passed('shared-preview URLs get early noindex, including API failure')
  # Make sure new metadata does not interfere with the actual editor.
  page.goto(BASE+'/jowkari-sites/?quick=1&name=SEO+Release+QA&industry=Plumber&city=North+Vancouver',wait_until='domcontentloaded')
  expect(page.frame_locator('#siteFrame').locator('h1')).to_be_visible();expect(page.locator('#projectName')).to_have_text('SEO Release QA');passed('real Studio creation remains available after metadata update')
  # No real email, booking or payment is generated by these tests.
  received=[]
  def success(route):
   headers={'Access-Control-Allow-Origin':BASE,'Access-Control-Allow-Methods':'POST,OPTIONS','Access-Control-Allow-Headers':'content-type,accept'}
   if route.request.method=='OPTIONS':route.fulfill(status=204,headers=headers);return
   received.append(route.request.post_data_json);route.fulfill(status=200,headers=headers,json={'success':True})
  context.route('https://api.web3forms.com/submit',success)
  page.goto(BASE+'/contact.html?utm_source=google&utm_medium=organic&utm_campaign=gbp')
  form=page.locator('.leadForm');form.locator('[name=name]').fill('SEO test, not a real lead');form.locator('[name=business]').fill('Synthetic QA');form.locator('[name=email]').fill('qa@example.com');form.locator('[name=message]').fill('Mock provider test only.');form.locator('[type=submit]').click()
  expect(form.locator('.formStatus')).to_have_class('formStatus ok')
  assert len(received)==1 and received[0]['utm_source']=='google' and received[0]['utm_campaign']=='gbp' and received[0]['source_page']=='/contact.html'
  passed('new contact form includes campaign attribution and source page (mock provider)')
  context.unroute('https://api.web3forms.com/submit',success);context.route('https://api.web3forms.com/submit',lambda route:route.abort('failed'))
  page.goto(BASE+'/contact.html');form=page.locator('.leadForm');form.locator('[name=name]').fill('Keep me');form.locator('[name=business]').fill('QA');form.locator('[name=email]').fill('qa@example.com');form.locator('[name=message]').fill('Keep my draft');form.locator('[type=submit]').click()
  expect(form.locator('.formStatus')).to_have_class('formStatus err');expect(form.locator('[name=message]')).to_have_value('Keep my draft');expect(form.locator('[type=submit]')).to_be_enabled();passed('failed enquiry keeps the entered data and permits retry')
  for path in ['/demo/roofing/','/demo/plumbing/','/demo/electrician/']:
   page.goto(BASE+path,wait_until='domcontentloaded');expect(page.locator('h1')).to_be_visible();assert 'noindex' in page.locator('meta[name=robots]').first.get_attribute('content')
  passed('all three existing demo pages still render and remain noindex')
  assert not errors,errors;passed('no uncaught JavaScript errors in tested website, form or editor flows')
  (OUT/'browser.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'errors':errors,'scope':'Chromium over HTTP; form delivery mocked, not inbox receipt.'},indent=2))
 except Exception:
  page.screenshot(path=str(OUT/'failure.png'),full_page=True);print('BROWSER ERRORS',errors,flush=True);raise
 finally:context.tracing.stop(path=str(OUT/'trace.zip'));browser.close();server.shutdown()
